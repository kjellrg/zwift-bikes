// Generates .cspell/zwift-data-words.txt from the installed zwift-data package:
// every word that appears in a route, segment, world, frame or wheel name.
// Runs from the postinstall hook (alongside `nuxt prepare`), so the dictionary
// always matches the installed zwift-data version and never needs hand-curation
// - new routes arrive with the Renovate bump that ships them. The output is
// gitignored for the same reason .nuxt/ is: it is derived, not authored.
import { writeFile, mkdir } from 'node:fs/promises'
import {
  bikeFrames,
  bikeFrontWheels,
  bikeRearWheels,
  routes,
  segments,
  worlds
} from 'zwift-data'

const names = [
  ...routes,
  ...segments,
  ...worlds,
  ...bikeFrames,
  ...bikeFrontWheels,
  ...bikeRearWheels
].map(entry => entry.name)

const words = new Set()
for (const name of names) {
  // Split on anything that is not a letter (Unicode-aware, so Église and Pavé
  // survive intact). Two-letter fragments and shorter are below cspell's
  // minimum word length and would only bloat the file.
  for (const word of name.split(/[^\p{L}]+/u)) {
    if (word.length >= 3) words.add(word)
  }
}

const sorted = [...words].sort((a, b) => a.localeCompare(b, 'en'))
const header
  = '# Generated by scripts/spell/generate-zwift-dict.mjs - do not edit.\n'

await mkdir(new URL('../../.cspell/', import.meta.url), { recursive: true })
await writeFile(
  new URL('../../.cspell/zwift-data-words.txt', import.meta.url),
  header + sorted.join('\n') + '\n'
)
console.log(`zwift-data dictionary: ${sorted.length} words`)
